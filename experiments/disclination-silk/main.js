import { NematicSilkSimulation, DEFAULT_PARAMS } from './simulation.js';
import { SilkRenderer, FlatSilkRenderer } from './renderer.js';

const $ = id => document.getElementById(id);
$('guide').href = new URL('./README.md',import.meta.url).href;
const query = new URLSearchParams(location.search);
const mobile = matchMedia('(max-width:800px), (pointer:coarse)').matches;
const params = { ...DEFAULT_PARAMS };
const settings = { quality: mobile ? 72 : 104, speed: 1, polarizer: 24, view: 0, source: true };
if ([72,104,144].includes(Number(query.get('quality')))) settings.quality = Number(query.get('quality'));
const sourceColors = ['#111528','#45449e','#8d78fa','#e493e5','#ffca9c','#c8f2e0','#58ddd7','#578be0'];
const palettes = new Map([['source',sourceColors]]);
const controlDefs = [
  ['activity','Active stress',-2,2.5,.05,'Reverse or strengthen the self-driven flow.'],
  ['elasticity','Orientational elasticity',.1,1.4,.02,'Trade fine defects for smooth alignment.'],
  ['growth','Fiber growth',0,2,.05,'Change the extension of actual retained paths.'],
  ['stiffness','Fiber spring stiffness',0,4,.05,'Change tension generated by chain extension.'],
  ['feedback','Stress → director',0,2,.05,'Let fiber mechanics change future alignment.'],
  ['nutrient','Nutrient reservoir',0,1,.02,'Supply the material used by growing tips.'],
  ['speed','Evolution speed',0,3,.05,'Independent rate of fixed simulation steps.'],
  ['polarizer','Crossed-polarizer angle',0,180,1,'Rotate optical extinction without altering state.'],
];
let canvas = $('art'), renderer, sim, bytes, canvasEvents, pointer;
let paused = matchMedia('(prefers-reduced-motion:reduce)').matches, busy = false, lost = false, dirty = true;
let last = performance.now(), debt = 0, frameCount = 0, statStamp = last, fps = 0;

for (const [key,title,min,max,step,hint] of controlDefs) {
  const target = key in settings ? settings : params;
  if (query.has(key) && Number.isFinite(Number(query.get(key)))) target[key] = Math.max(min,Math.min(max,Number(query.get(key))));
  const control = document.createElement('div'); control.className = 'control';
  control.innerHTML = `<label for="${key}">${title}<output id="out-${key}"></output></label><input id="${key}" type="range" min="${min}" max="${max}" step="${step}"><small>${hint}</small>`;
  $(key === 'speed' || key === 'polarizer' ? 'observation' : 'sliders').append(control);
  $(key).value = target[key];
  $(key).addEventListener('input', () => {
    target[key] = Number($(key).value); if (key === 'polarizer') dirty = true;
    updateOutputs(); remember();
  });
}
function updateOutputs() {
  for (const [key] of controlDefs) {
    const value = key in settings ? settings[key] : params[key];
    $('out-'+key).value = key === 'polarizer' ? `${value.toFixed(0)}°` : value.toFixed(2);
  }
}
function remember() {
  const q = new URLSearchParams({ seed: $('seed').value, quality: String(settings.quality), palette: $('palette').value });
  for (const [key] of controlDefs) q.set(key,String(key in settings ? settings[key] : params[key]));
  // Preserve explicit fallback / diagnostic modes through reseeds.
  for (const flag of ['flat','diagnostics']) if (query.has(flag)) q.set(flag,'1');
  history.replaceState(null,'',`${location.pathname}?${q}`);
}
function makeRenderer() {
  canvasEvents?.abort(); canvasEvents = new AbortController();
  try {
    if (query.has('flat')) throw new Error('Reduced map requested');
    renderer = new SilkRenderer(canvas);
  } catch (error) {
    if (!query.has('flat')) console.warn('Using Canvas silk fallback:',error.message);
    const replacement = canvas.cloneNode(); canvas.replaceWith(replacement); canvas = replacement;
    renderer = new FlatSilkRenderer(canvas);
  }
  renderer.setPalette(palettes.get($('palette').value) || sourceColors);
  const options = { signal: canvasEvents.signal };
  canvas.addEventListener('webglcontextlost',event => {
    event.preventDefault(); lost = true; pointer = null;
    $('status').textContent = 'Graphics context lost · material retained';
  },options);
  canvas.addEventListener('webglcontextrestored',() => {
    lost = false; makeRenderer(); dirty = true; last = performance.now(); debt = 0; updateStatus();
  },options);
  canvas.addEventListener('pointerdown',event => {
    if (busy || lost) return;
    canvas.setPointerCapture(event.pointerId);
    pointer = { id: event.pointerId, x: event.clientX, y: event.clientY }; paint();
  },options);
  canvas.addEventListener('pointermove',event => {
    if (pointer?.id !== event.pointerId) return;
    pointer.x = event.clientX; pointer.y = event.clientY; paint();
  },options);
  for (const type of ['pointerup','pointercancel','lostpointercapture']) canvas.addEventListener(type,() => pointer = null,options);
}
function paint() {
  if (!pointer || !sim || busy || lost) return;
  const r = canvas.getBoundingClientRect();
  const uv = renderer.pointer((pointer.x-r.left)/r.width,(pointer.y-r.top)/r.height);
  if (uv) { sim.inject(...uv,$('brush').value); dirty = true; }
}
function updateStatus() {
  if (!sim || busy || lost) return;
  $('status').textContent = `${paused ? 'Paused' : settings.speed === 0 ? 'Speed zero' : 'Weaving'} · ${renderer.backend} · drag to ${$('brush').value}`;
}
async function regrow(seed) {
  if (busy) return;
  busy = true; pointer = null; $('status').textContent = 'Preparing nematic order and fiber seeds…';
  const ids = ['seed','reseed','mutate','quality',...controlDefs.map(c=>c[0])];
  for (const id of ids) $(id).disabled = true;
  await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  try {
    seed = Number.isFinite(Number(seed)) ? Number(seed) >>> 0 : 241907; $('seed').value = seed;
    sim = new NematicSilkSimulation(settings.quality,seed,params); sim.params = params;
    bytes = new Uint8Array(sim.size*sim.size*4); debt = 0; last = performance.now(); dirty = true; remember();
  } catch (error) { $('status').textContent = `Initialization failed: ${error.message}`; console.error(error); }
  finally { busy = false; for (const id of ids) $(id).disabled = false; updateStatus(); }
}
$('pause').textContent = paused ? 'Resume' : 'Pause'; $('pause').setAttribute('aria-pressed',String(paused));
$('pause').addEventListener('click',() => {
  paused = !paused; $('pause').textContent = paused ? 'Resume' : 'Pause';
  $('pause').setAttribute('aria-pressed',String(paused)); debt = 0; updateStatus();
});
$('reseed').addEventListener('click',() => regrow($('seed').value));
$('seed').addEventListener('keydown',event => { if (event.key === 'Enter') regrow($('seed').value); });
$('mutate').addEventListener('click',() => {
  const random = new Uint32Array(6); crypto.getRandomValues(random); const r = i => random[i]/4294967296;
  params.activity = -.8+r(1)*3.1; params.elasticity = .25+r(2)*.75;
  params.growth = .6+r(3)*1.15; params.stiffness = .5+r(4)*2.8; params.feedback = .2+r(5)*1.5;
  for (const [key] of controlDefs) $(key).value = key in settings ? settings[key] : params[key];
  updateOutputs(); regrow(random[0]);
});
$('quality').value = settings.quality;
$('quality').addEventListener('change',() => { settings.quality = Number($('quality').value); regrow($('seed').value); });
$('view').addEventListener('change',() => { settings.view = Number($('view').value); dirty = true; });
$('brush').addEventListener('change',updateStatus);
$('palette').addEventListener('change',() => {
  renderer.setPalette(palettes.get($('palette').value)||sourceColors);
  settings.source = $('palette').value === 'source'; dirty = true; remember();
});
$('snapshot').addEventListener('click',() => {
  if (!sim || busy || lost) return;
  renderer.draw(sim,sim.encode(bytes),settings);
  canvas.toBlob(blob => {
    if (!blob) { $('status').textContent = 'PNG export unavailable'; return; }
    const url = URL.createObjectURL(blob), a = document.createElement('a'); a.href = url;
    a.download = `argon-silk-${sim.seed}-${sim.steps}.png`; a.click(); setTimeout(()=>URL.revokeObjectURL(url),10000);
  },'image/png');
});
document.addEventListener('keydown',event => {
  if (event.code === 'Space' && !/INPUT|SELECT|BUTTON|SUMMARY/.test(document.activeElement.tagName)) { event.preventDefault(); $('pause').click(); }
});
document.addEventListener('visibilitychange',() => { last = performance.now(); debt = 0; });
window.addEventListener('resize',() => dirty = true);

async function loadPalettes() {
  try {
    const response = await fetch(new URL('../../data/mathemagical-palettes.json',import.meta.url));
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    for (const p of data.palettes) {
      palettes.set(p.id,p.colors); const option = document.createElement('option'); option.value = p.id;
      option.textContent = `${p.name} · ${p.id}`; $('palette').append(option);
    }
    const desired = query.get('palette');
    if (desired && palettes.has(desired)) {
      $('palette').value = desired; settings.source = desired === 'source'; renderer.setPalette(palettes.get(desired)); dirty = true;
    }
  } catch (error) { console.warn('Shared palettes unavailable; source palette retained:',error.message); }
}
function frame(now) {
  requestAnimationFrame(frame); const elapsed = Math.min(.05,Math.max(0,(now-last)/1000)); last = now;
  if (!sim || busy || lost || document.hidden) return;
  if (!paused && settings.speed > 0) {
    debt = Math.min(5,debt+elapsed*48*settings.speed); const start = performance.now(); let count = 0;
    while (debt >= 1 && performance.now()-start < 12) { sim.step(); debt--; count++; }
    if (count) dirty = true;
  }
  if (dirty) { renderer.draw(sim,sim.encode(bytes),settings); dirty = false; frameCount++; }
  if (now-statStamp > 750) {
    fps = Math.round(frameCount*1000/(now-statStamp)); frameCount = 0; statStamp = now;
    const s = sim.stats(); $('age').textContent = `${s.time.toFixed(1)} τ`;
    $('metrics').textContent = `${s.defectsPositive}+ / ${s.defectsNegative}− DEFECTS · ${s.segments} SEGMENTS · ${fps} FPS`;
    updateStatus();
  }
}
updateOutputs();
try { makeRenderer(); loadPalettes(); requestAnimationFrame(frame); regrow(query.get('seed')??241907); }
catch (error) { $('status').textContent = `Browser graphics unavailable: ${error.message}`; console.error(error); }
if (query.has('diagnostics')) Object.defineProperty(window,'argonSilk',{value:{stats:()=>sim?.stats(),settings:()=>({...settings,paused}),backend:()=>renderer?.backend}});
